import argparse
import json
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd

from data_preprocessing.path_utils import resolve_manifest_artifact_path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Upsample and augment converted panel CSV datasets into denser synthetic datasets."
    )
    parser.add_argument(
        "--manifest",
        required=True,
        help="Path to the source manifest.json generated by convert_wechat_raw_to_csv.py.",
    )
    parser.add_argument(
        "--output-dir",
        default="data_preprocessing/output/shanse001",
        help="Directory for augmented datasets and the new manifest.",
    )
    parser.add_argument(
        "--target-interval-minutes",
        type=int,
        default=1,
        help="Target synthetic sampling interval in minutes.",
    )
    parser.add_argument(
        "--variants-per-dataset",
        type=int,
        default=2,
        help="Number of augmented variants to generate per source dataset, in addition to the base upsampled version.",
    )
    parser.add_argument(
        "--current-jitter-std",
        type=float,
        default=0.03,
        help="Relative noise scale for branch current augmentation.",
    )
    parser.add_argument(
        "--power-jitter-std",
        type=float,
        default=0.02,
        help="Relative noise scale for branch power augmentation.",
    )
    parser.add_argument(
        "--random-seed",
        type=int,
        default=42,
        help="Random seed for reproducible synthetic variants.",
    )
    parser.add_argument(
        "--dataset-prefix",
        default="shanse001",
        help="Prefix used when naming the exported synthetic datasets.",
    )
    return parser.parse_args()


def load_manifest(manifest_path: Path) -> List[Dict[str, object]]:
    payload = json.loads(manifest_path.read_text())
    return list(payload.get("datasets", []))


def resolve_csv_path(manifest_path: Path, csv_path_value: str) -> Path:
    return resolve_manifest_artifact_path(manifest_path, csv_path_value)


def branch_indices(columns: List[str]) -> List[int]:
    found = []
    for column in columns:
        if column.startswith("branch_") and column.endswith("_power"):
            found.append(int(column.split("_")[1]))
    return sorted(found)


def compact_source_name(source_name: str) -> str:
    if source_name.startswith("panel_"):
        return "panel"
    return source_name


def build_time_index(frame: pd.DataFrame) -> pd.DataFrame:
    result = frame.copy()
    result["timestamp"] = pd.to_datetime(result["timestamp"])
    result = result.sort_values("timestamp").drop_duplicates(subset="timestamp")
    return result.set_index("timestamp")


def upsample_dataset(frame: pd.DataFrame, target_interval_minutes: int) -> Tuple[pd.DataFrame, int]:
    indexed = build_time_index(frame)
    inferred_base = int(
        pd.Series(indexed.index).diff().dropna().dt.total_seconds().median() // 60
    )
    target_rule = f"{target_interval_minutes}min"
    upsampled = indexed.resample(target_rule).asfreq()
    numeric_cols = upsampled.columns.tolist()
    upsampled[numeric_cols] = upsampled[numeric_cols].interpolate(method="time", limit_direction="both")
    upsampled = upsampled.reset_index()
    return upsampled, inferred_base


def smooth_noise(
    length: int,
    std: float,
    kernel_size: int,
    rng: np.random.Generator,
) -> np.ndarray:
    raw = rng.normal(0.0, std, size=length).astype(np.float32)
    kernel = np.ones(kernel_size, dtype=np.float32) / float(kernel_size)
    return np.convolve(raw, kernel, mode="same")


def augment_dataset(
    frame: pd.DataFrame,
    variant_index: int,
    current_jitter_std: float,
    power_jitter_std: float,
    rng: np.random.Generator,
) -> pd.DataFrame:
    augmented = frame.copy()
    indices = branch_indices(augmented.columns.tolist())
    length = len(augmented)
    current_kernel = max(5, min(31, length // 40 * 2 + 1))
    power_kernel = max(5, min(25, length // 50 * 2 + 1))

    for branch_index in indices:
        power_col = f"branch_{branch_index}_power"
        current_col = f"branch_{branch_index}_current"
        power_scale = 1.0 + smooth_noise(length, power_jitter_std, power_kernel, rng)
        current_scale = 1.0 + smooth_noise(length, current_jitter_std, current_kernel, rng)
        augmented[power_col] = np.maximum(augmented[power_col].to_numpy(dtype=np.float32) * power_scale, 0.0)
        augmented[current_col] = np.maximum(augmented[current_col].to_numpy(dtype=np.float32) * current_scale, 0.0)

    power_cols = [f"branch_{idx}_power" for idx in indices]
    current_cols = [f"branch_{idx}_current" for idx in indices]
    augmented["total_power"] = augmented[power_cols].sum(axis=1)
    augmented["total_residual_current"] = augmented[current_cols].sum(axis=1)
    augmented["synthetic_variant"] = variant_index
    return augmented


def write_dataset_bundle(
    *,
    dataset_name: str,
    output_dir: Path,
    base_upsampled: pd.DataFrame,
    augmented_variants: List[pd.DataFrame],
    source_info: Dict[str, object],
    base_interval_minutes: int,
    target_interval_minutes: int,
) -> Dict[str, object]:
    dataset_dir = output_dir / dataset_name
    dataset_dir.mkdir(parents=True, exist_ok=True)

    base_csv_path = dataset_dir / f"{dataset_name}.base.csv"
    base_output = base_upsampled.copy()
    base_output["synthetic_variant"] = 0
    base_output["segment_id"] = f"{dataset_name}_base"
    base_output.to_csv(base_csv_path, index=False)

    variant_paths = []
    for variant_frame in augmented_variants:
        variant_id = int(variant_frame["synthetic_variant"].iloc[0])
        variant_path = dataset_dir / f"{dataset_name}.variant_{variant_id}.csv"
        variant_frame = variant_frame.copy()
        variant_frame["segment_id"] = f"{dataset_name}_variant_{variant_id}"
        variant_frame.to_csv(variant_path, index=False)
        variant_paths.append(str(variant_path))

    combined_csv_path = dataset_dir / f"{dataset_name}.csv"
    combined_output = pd.concat([base_output] + [pd.read_csv(path) for path in variant_paths], ignore_index=True)
    combined_output.to_csv(combined_csv_path, index=False)

    metadata = {
        "dataset_name": dataset_name,
        "source_dataset_name": source_info["dataset_name"],
        "source_csv_path": source_info["csv_path"],
        "source_num_branches": source_info["num_branches"],
        "base_interval_minutes": base_interval_minutes,
        "target_interval_minutes": target_interval_minutes,
        "base_rows": len(base_upsampled),
        "augmented_variant_count": len(augmented_variants),
        "combined_rows": len(combined_output),
        "base_csv_path": str(base_csv_path),
        "combined_csv_path": str(combined_csv_path),
        "variant_csv_paths": variant_paths,
        "notes": [
            "This dataset is synthetically upsampled from a lower-frequency observed panel.",
            "Use it as an augmentation dataset, not as evidence that the original hardware sampled at the target interval.",
            "Training should use the combined CSV, which includes segment_id to prevent windows from crossing augmentation boundaries.",
        ],
    }
    metadata_path = dataset_dir / f"{dataset_name}.metadata.json"
    metadata_path.write_text(json.dumps(metadata, indent=2))
    return {
        "dataset_name": dataset_name,
        "csv_path": str(combined_csv_path),
        "metadata_path": str(metadata_path),
        "num_branches": source_info["num_branches"],
        "dataset_rows_kept": len(combined_output),
        "grid_rows_total": len(combined_output),
        "grid_start": str(base_upsampled["timestamp"].iloc[0]),
        "grid_end": str(base_upsampled["timestamp"].iloc[-1]),
        "synthetic_variants": len(augmented_variants),
        "variant_csv_paths": variant_paths,
        "base_csv_path": str(base_csv_path),
        "source_dataset_name": source_info["dataset_name"],
        "target_interval_minutes": target_interval_minutes,
        "base_interval_minutes": base_interval_minutes,
    }


def main() -> None:
    args = parse_args()
    rng = np.random.default_rng(args.random_seed)
    manifest_path = Path(args.manifest).resolve()
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    source_datasets = load_manifest(manifest_path)
    results = []
    for source_info in source_datasets:
        csv_path = resolve_csv_path(manifest_path, str(source_info["csv_path"]))
        frame = pd.read_csv(csv_path)
        base_upsampled, base_interval_minutes = upsample_dataset(
            frame=frame,
            target_interval_minutes=args.target_interval_minutes,
        )
        synthetic_name = f"{args.dataset_prefix}_{compact_source_name(str(source_info['dataset_name']))}_{args.target_interval_minutes}min"
        variants = []
        for variant_index in range(1, args.variants_per_dataset + 1):
            variant_rng = np.random.default_rng(rng.integers(0, 2**31 - 1))
            variants.append(
                augment_dataset(
                    frame=base_upsampled,
                    variant_index=variant_index,
                    current_jitter_std=args.current_jitter_std,
                    power_jitter_std=args.power_jitter_std,
                    rng=variant_rng,
                )
            )
        result = write_dataset_bundle(
            dataset_name=synthetic_name,
            output_dir=output_dir,
            base_upsampled=base_upsampled,
            augmented_variants=variants,
            source_info=source_info,
            base_interval_minutes=base_interval_minutes,
            target_interval_minutes=args.target_interval_minutes,
        )
        results.append(result)
        print(
            f"{synthetic_name}: base_rows={result['dataset_rows_kept']}, "
            f"variants={result['synthetic_variants']}, "
            f"range={result['grid_start']} -> {result['grid_end']}"
        )

    manifest_payload = {
        "generated_from_manifest": str(manifest_path),
        "target_interval_minutes": args.target_interval_minutes,
        "variants_per_dataset": args.variants_per_dataset,
        "datasets": results,
    }
    manifest_out = output_dir / "manifest.json"
    manifest_out.write_text(json.dumps(manifest_payload, indent=2))
    print(f"Wrote synthetic manifest to {manifest_out}")


if __name__ == "__main__":
    main()
